// Exports the two film graphs (fictional contacts, fictional 24-cell circuit) for the website quest and lab.
// Positions are rescaled into the site's 740×530 drawing box; every result shown on the site is recomputed live.
import fs from 'node:fs/promises';
const d=JSON.parse(await fs.readFile(new URL('../data/film-v3.json',import.meta.url)));
const fit=(pos,[x0,y0,x1,y1])=>{const v=Object.values(pos),xs=v.map(p=>p[0]),ys=v.map(p=>p[1]);
  const mx=Math.min(...xs),Mx=Math.max(...xs),my=Math.min(...ys),My=Math.max(...ys),s=Math.min((x1-x0)/(Mx-mx),(y1-y0)/(My-my));
  const ox=x0+((x1-x0)-(Mx-mx)*s)/2,oy=y0+((y1-y0)-(My-my)*s)/2;
  return Object.fromEntries(Object.entries(pos).map(([k,[x,y]])=>[k,[Math.round(ox+(x-mx)*s),Math.round(oy+(y-my)*s)]]));};
// Push apart nodes whose name labels would collide; keeps the overall shape.
const relax=(pos,min=56,[x0,y0,x1,y1]=[40,40,700,470])=>{const P=structuredClone(pos),k=Object.keys(P);
  for(let it=0;it<300;it++){let moved=false;
    for(let i=0;i<k.length;i++)for(let j=i+1;j<k.length;j++){const a=P[k[i]],b=P[k[j]],dx=b[0]-a[0],dy=(b[1]-a[1])*1.2,d=Math.hypot(dx,dy)||1;
      if(d<min){const f=(min-d)/2/d;a[0]-=dx*f;a[1]-=dy*f/1.2;b[0]+=dx*f;b[1]+=dy*f/1.2;moved=true;}}
    for(const q of Object.values(P)){q[0]=Math.min(x1,Math.max(x0,q[0]));q[1]=Math.min(y1,Math.max(y0,q[1]));}
    if(!moved)break;}
  return Object.fromEntries(Object.entries(P).map(([n,[x,y]])=>[n,[Math.round(x),Math.round(y)]]));};
const s=d.social,g=d.graph;
const CONTACTS={id:'contacts',name:'虚构通讯录（28 人）',nodes:s.graph.nodes,edges:s.graph.edges,names:s.names,
  positions:relax(fit(s.scatter,[40,40,700,470])),gathered:relax(fit(s.gather,[40,50,700,470]),50)};
const CHIP={id:'chip',name:'虚构 24 单元电路',nodes:g.nodes,edges:g.edges,positions:relax(fit(g.positions,[50,40,690,470]),60),
  ruler:d.geometric.labels};
const src=`// Generated by scripts/build-site-graphs.mjs from data/film-v3.json. Do not edit by hand.
export const CONTACTS=${JSON.stringify(CONTACTS)};
export const CHIP=${JSON.stringify(CHIP)};
`;
await fs.writeFile(new URL('../site/film-graphs.js',import.meta.url),src);
console.log('contacts',CONTACTS.nodes.length,CONTACTS.edges.length,'chip',CHIP.nodes.length,CHIP.edges.length);
